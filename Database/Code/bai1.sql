CREATE TABLE CHUONGTRINH (
  MACT CHAR(5) PRIMARY KEY,
  TENCT VARCHAR2(50) NOT NULL
);
CREATE TABLE LOAILOP (
  MALOAI CHAR(5) PRIMARY KEY,
  MACT CHAR(5) NOT NULL REFERENCES CHUONGTRINH(MACT),
  TENLOAI VARCHAR2(50) NOT NULL
);
CREATE TABLE LOP (
  MALOP CHAR(5) PRIMARY KEY,
  MALOAI CHAR(5) NOT NULL,
  TENLOP VARCHAR2(50) NOT NULL,
  SISO NUMBER CHECK (SISO > 12),
  MAKH CHAR(4) REFERENCES KHOAHOC(MAKH),
  FOREIGN KEY (MALOAI) REFERENCES LOAILOP(MALOAI)
);
CREATE TABLE HOCVIEN (
  MAHV CHAR(6) PRIMARY KEY,
  TENHV VARCHAR2(50) NOT NULL,
  GIOITINH NUMBER(1) CHECK (GIOITINH IN (0,1)),
  NGAYSINH DATE,
  SDT VARCHAR2(15),
  DIACHI VARCHAR2(100)
);
CREATE TABLE PHIEUTHU (
  SOPT CHAR(8) PRIMARY KEY,
  MAHV CHAR(6) NOT NULL,
  MALOP CHAR(5) NOT NULL,
  NGAYLAPPHIEU DATE,
  THANHTIEN NUMBER(12,2) CHECK (THANHTIEN > 0),
  FOREIGN KEY (MAHV) REFERENCES HOCVIEN(MAHV),
  FOREIGN KEY (MALOP) REFERENCES LOP(MALOP)
);
CREATE TABLE MONHOC (
  MAMH CHAR(5) PRIMARY KEY,
  TENMH VARCHAR2(50) NOT NULL
);
CREATE TABLE DIEM (
  MAMH CHAR(5),
  MAHV CHAR(6),
  MALOP CHAR(5),
  DIEM NUMBER(3,1) CHECK (DIEM BETWEEN 0 AND 10),
  PRIMARY KEY (MAMH, MAHV, MALOP),
  FOREIGN KEY (MAMH) REFERENCES MONHOC(MAMH),
  FOREIGN KEY (MAHV) REFERENCES HOCVIEN(MAHV),
  FOREIGN KEY (MALOP) REFERENCES LOP(MALOP)
);
