SELECT AVG(D.DIEM) AS DIEM_TRUNGBINH
FROM DIEM D
JOIN HOCVIEN HV ON D.MAHV = HV.MAHV
JOIN LOP L ON D.MALOP = L.MALOP
JOIN LOAILOP LL ON L.MALOAI = LL.MALOAI
WHERE HV.TENHV = 'Đỗ Gia Bảo'
AND HV.NGAYSINH = TO_DATE('2001-12-02','YYYY-MM-DD')
AND L.TENLOP = 'Lớp 1'
AND LL.TENLOAI = 'Tiếng Anh căn bản';