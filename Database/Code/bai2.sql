FROM HOCVIEN HV
JOIN DIEM D ON HV.MAHV = D.MAHV
JOIN MONHOC MH ON D.MAMH = MH.MAMH
JOIN LOP L ON D.MALOP = L.MALOP
JOIN KHOAHOC KH ON L.MAKH = KH.MAKH
WHERE KH.TENKH = 'Khóa 1';
